// Atribuição Simples (=)
let pontuacaoUsuario = 0; // Inicialização
pontuacaoUsuario = 50; // Atribuiçao de um valor

console.log(pontuacaoUsuario); // 50

//-----------------------------------------

// Atribuição de Adição (+=)
let totalCarrinho = 100.0;
// O cliente adicionou um itm de 50.00
totalCarrinho += 50.0;
console.log(totalCarrinho); // 150,00

//-----------------------------------------

// Atribuição de Subtração (-=)
let creditosDisponiveis = 10.0;
// O usuario consumiu uma unidade de credito
creditosDisponiveis -= 1.0;
console.log(creditosDisponiveis); // 9.00

//-----------------------------------------

// Atribuição de Multiplicação (*=) e Divisão (/=)
let fatorEscala = 2;
fatorEscala *= 3;
console.log(fatorEscala); // 6

fatorEscala /= 2;
console.log(fatorEscala); // 3

//-----------------------------------------

// Atribuição de Resto (%=) e Exponenciação (**=)
let ciclo = 10;

ciclo %= 3;
console.log(ciclo); // 1
